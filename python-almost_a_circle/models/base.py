#!/usr/bin/python3
"""Module that defines the Base class.

The Base class manages the id attribute of all the other classes of the
project and handles their JSON representation and storage in files.
"""
import json


class Base:
    """Base of all the other classes of this project.

    Private class attribute:
        __nb_objects (int): number of instances created without an id.

    Attributes:
        id (int): the identifier of the instance.
    """

    __nb_objects = 0

    def __init__(self, id=None):
        """Initialize a new Base.

        Args:
            id (int): the id of the instance. If None, a new id is
                generated by incrementing the number of objects.
        """
        if id is not None:
            self.id = id
        else:
            Base.__nb_objects += 1
            self.id = Base.__nb_objects

    @staticmethod
    def to_json_string(list_dictionaries):
        """Return the JSON string representation of a list of dictionaries.

        Args:
            list_dictionaries (list): a list of dictionaries.

        Returns:
            "[]" if list_dictionaries is None or empty, otherwise its JSON
            string representation.
        """
        if list_dictionaries is None or len(list_dictionaries) == 0:
            return "[]"
        return json.dumps(list_dictionaries)

    @classmethod
    def save_to_file(cls, list_objs):
        """Write the JSON representation of a list of instances to a file.

        The file is named <Class name>.json and is overwritten if it exists.

        Args:
            list_objs (list): a list of instances inheriting from Base.
                If None, an empty list is saved.
        """
        if list_objs is None:
            list_objs = []
        dictionaries = [obj.to_dictionary() for obj in list_objs]
        with open(cls.__name__ + ".json", "w", encoding="utf-8") as file:
            file.write(cls.to_json_string(dictionaries))

    @staticmethod
    def from_json_string(json_string):
        """Return the list represented by a JSON string.

        Args:
            json_string (str): a JSON string representing a list of
                dictionaries.

        Returns:
            An empty list if json_string is None or empty, otherwise the
            list represented by json_string.
        """
        if json_string is None or len(json_string) == 0:
            return []
        return json.loads(json_string)

    @classmethod
    def create(cls, **dictionary):
        """Return a new instance with all its attributes already set.

        A "dummy" instance is created with mandatory attributes, then
        updated with the values of dictionary.

        Args:
            **dictionary: the attributes to set, as key/value pairs.

        Returns:
            The new instance of cls.
        """
        if cls.__name__ == "Rectangle":
            dummy = cls(1, 1)
        elif cls.__name__ == "Square":
            dummy = cls(1)
        else:
            dummy = cls()
        dummy.update(**dictionary)
        return dummy

    @classmethod
    def load_from_file(cls):
        """Return a list of instances loaded from the file <Class name>.json.

        Returns:
            An empty list if the file does not exist, otherwise the list of
            instances of cls described in the file.
        """
        try:
            with open(cls.__name__ + ".json", "r", encoding="utf-8") as file:
                content = file.read()
        except FileNotFoundError:
            return []
        return [cls.create(**item) for item in cls.from_json_string(content)]
